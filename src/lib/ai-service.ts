import { LANGUAGES, meetings, type Meeting } from "./mock-data";

/* ---------------- Meeting minutes (MOM) ---------------- */

export function generateMOM(m: Meeting) {
  return [
    `# Minutes of Meeting — ${m.title}`,
    ``,
    `**Date:** ${new Date(m.date).toLocaleString("en-US")}`,
    `**Platform:** ${m.platform}  |  **Duration:** ${m.duration}`,
    `**Languages:** ${m.languages.join(", ")}`,
    `**Participants:** ${m.participants.join(", ")}`,
    ``,
    `## 1. Executive summary`,
    m.summary,
    ``,
    `## 2. Key discussion points`,
    ...m.points.map((p, i) => `${i + 1}. ${p}`),
    ``,
    `## 3. Decisions taken`,
    ...m.decisions.map((d, i) => `${i + 1}. ${d}`),
    ``,
    `## 4. Action items`,
    `| # | Task | Owner | Due | Priority | Status |`,
    `| - | ---- | ----- | --- | -------- | ------ |`,
    ...m.actionItems.map(
      (a, i) => `| ${i + 1} | ${a.task} | ${a.owner} | ${a.due} | ${a.priority} | ${a.status} |`,
    ),
    ``,
    `## 5. Next steps`,
    ...m.nextSteps.map((n) => `- ${n}`),
    ``,
    `---`,
    `Generated by MeetMind AI · sentiment ${m.sentiment} (${Math.round(m.sentimentScore * 100)}%)`,
  ].join("\n");
}

/* ---------------- Follow-up email ---------------- */

export function generateEmail(m: Meeting) {
  const open = m.actionItems.filter((a) => !a.done);
  return [
    `Subject: ${m.title} — summary, decisions and next steps`,
    ``,
    `Hi team,`,
    ``,
    `Thanks for joining the ${m.title.toLowerCase()} on ${new Date(m.date).toLocaleDateString("en-US", { month: "long", day: "numeric" })}. Here is the recap.`,
    ``,
    `Summary`,
    m.summary,
    ``,
    `Decisions`,
    ...m.decisions.map((d) => `• ${d}`),
    ``,
    `Open action items`,
    ...open.map((a) => `• ${a.task} — ${a.owner} (due ${a.due}, ${a.priority.toLowerCase()} priority)`),
    ``,
    `Next steps`,
    ...m.nextSteps.map((n) => `• ${n}`),
    ``,
    `Full transcript, ${m.languages.join(" / ")} translations and analytics are available in MeetMind AI.`,
    ``,
    `Best regards,`,
    `${m.speakers[0]?.name ?? "Aarav Mehta"}`,
    `${m.speakers[0]?.role ?? "Product Lead"}`,
  ].join("\n");
}

/* ---------------- Jira tasks ---------------- */

export type JiraTask = {
  key: string;
  type: "Task" | "Bug" | "Story";
  summary: string;
  assignee: string;
  priority: string;
  due: string;
  storyPoints: number;
  labels: string[];
  description: string;
};

export function generateJiraTasks(m: Meeting): JiraTask[] {
  return m.actionItems.map((a, i) => {
    const bug = /fix|regression|latency|bug|patch/i.test(a.task);
    return {
      key: `MEET-${1200 + i * 3}`,
      type: bug ? "Bug" : a.priority === "High" ? "Story" : "Task",
      summary: a.task,
      assignee: a.owner,
      priority: a.priority === "High" ? "Highest" : a.priority === "Medium" ? "Medium" : "Low",
      due: a.due,
      storyPoints: a.priority === "High" ? 5 : a.priority === "Medium" ? 3 : 2,
      labels: ["meetmind", m.platform.toLowerCase().replace(/\s+/g, "-")],
      description: `Auto-created from "${m.title}" (${new Date(m.date).toLocaleDateString("en-US")}).\n\nContext: ${m.decisions[i % Math.max(m.decisions.length, 1)] ?? m.summary.slice(0, 140)}`,
    };
  });
}

export function jiraCsv(tasks: JiraTask[]) {
  const rows = [
    ["Issue key", "Issue type", "Summary", "Assignee", "Priority", "Due date", "Story points", "Labels"],
    ...tasks.map((t) => [
      t.key,
      t.type,
      t.summary,
      t.assignee,
      t.priority,
      t.due,
      String(t.storyPoints),
      t.labels.join(" "),
    ]),
  ];
  return rows.map((r) => r.map((c) => `"${c.replace(/"/g, '""')}"`).join(",")).join("\n");
}

/* ---------------- Translation ---------------- */

export function languageName(code: string) {
  const l = LANGUAGES.find((x) => x.code === code);
  return l ? `${l.name} (${l.native})` : code;
}

export function getTranslation(m: Meeting, code: string) {
  return m.translations?.[code];
}

export function availableTranslations(m: Meeting) {
  return Object.keys(m.translations ?? {});
}

/* ---------------- Grounded chat answers ---------------- */

export type ChatAnswer = { text: string; sources: string[] };

const words = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 3);

function rank(query: string): Meeting[] {
  const q = words(query);
  return [...meetings]
    .map((m) => {
      const hay = [m.title, m.summary, ...m.keywords, ...m.decisions, ...m.points].join(" ").toLowerCase();
      return { m, score: q.reduce((s, w) => s + (hay.includes(w) ? 1 : 0), 0) };
    })
    .sort((a, b) => b.score - a.score)
    .filter((x, i) => x.score > 0 || i < 2)
    .slice(0, 3)
    .map((x) => x.m);
}

export function answerQuestion(query: string): ChatAnswer {
  const q = query.toLowerCase();
  const matches = rank(query);
  const primary = matches[0] ?? meetings[0]!;
  const sources = matches.map((m) => m.title);

  if (/action item|task|todo|to-do|due|owner|assign/.test(q)) {
    const items = matches.flatMap((m) => m.actionItems.map((a) => ({ a, m })));
    const open = items.filter((x) => !x.a.done);
    return {
      text: [
        `There are **${open.length} open action items** across ${matches.length} relevant meetings.`,
        ``,
        ...open
          .slice(0, 8)
          .map(
            (x, i) =>
              `${i + 1}. **${x.a.task}** — ${x.a.owner}, due ${x.a.due} (${x.a.priority} priority) · _${x.m.title}_`,
          ),
        ``,
        items.length - open.length > 0
          ? `${items.length - open.length} item(s) are already completed.`
          : `Nothing has been completed yet.`,
      ].join("\n"),
      sources,
    };
  }

  if (/decid|decision|agree|approve/.test(q)) {
    return {
      text: [
        `Here are the decisions recorded in **${primary.title}**:`,
        ``,
        ...primary.decisions.map((d, i) => `${i + 1}. ${d}`),
        ``,
        `Overall tone of the discussion was ${primary.sentiment.toLowerCase()} (${Math.round(primary.sentimentScore * 100)}% positive signal).`,
      ].join("\n"),
      sources,
    };
  }

  if (/block|risk|issue|problem|concern|delay/.test(q)) {
    const risky = primary.actionItems.filter((a) => a.priority === "High" && !a.done);
    return {
      text: [
        `The main risks surfaced in **${primary.title}**:`,
        ``,
        ...primary.points.slice(0, 3).map((p) => `• ${p}`),
        ``,
        risky.length
          ? `High-priority items still open:\n${risky.map((a) => `• ${a.task} — ${a.owner} (due ${a.due})`).join("\n")}`
          : `No high-priority items remain open.`,
      ].join("\n"),
      sources,
    };
  }

  if (/who|speak|talk|particip|team/.test(q)) {
    return {
      text: [
        `**${primary.title}** had ${primary.participants.length} participants. Speaking time:`,
        ``,
        ...primary.speakers.map(
          (s) => `• **${s.name}** (${s.role}) — ${s.minutes.toFixed(1)} min · ${s.sentiment.toLowerCase()} tone`,
        ),
      ].join("\n"),
      sources,
    };
  }

  if (/telugu|hindi|translat|language|multiling/.test(q)) {
    const codes = availableTranslations(primary);
    return {
      text: [
        `**${primary.title}** was captured in ${primary.languages.join(" and ")}.`,
        codes.length
          ? `Full translations are available in ${codes.map(languageName).join(", ")} — summary, key points, decisions, action items and the complete transcript.`
          : `No translation has been generated for this meeting yet.`,
        ``,
        `Telugu summary preview:`,
        getTranslation(primary, "te")?.summary?.slice(0, 320) ?? "—",
      ].join("\n"),
      sources,
    };
  }

  return {
    text: [
      `Here's what I found in **${primary.title}** (${new Date(primary.date).toLocaleDateString("en-US")}):`,
      ``,
      primary.summary,
      ``,
      `**Key points**`,
      ...primary.points.slice(0, 4).map((p) => `• ${p}`),
      ``,
      `${primary.decisions.length} decisions and ${primary.actionItems.length} action items were extracted from this meeting.`,
    ].join("\n"),
    sources,
  };
}

/* ---------------- Exports ---------------- */

export function downloadText(filename: string, content: string, mime = "text/plain") {
  const url = URL.createObjectURL(new Blob([content], { type: `${mime};charset=utf-8` }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

