export function exportPdf(m: Meeting) {
  const w = window.open("", "_blank", "width=900,height=1000");
  if (!w) return false;
  w.document.write(reportHtml(m));
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 400);
  return true;
}
